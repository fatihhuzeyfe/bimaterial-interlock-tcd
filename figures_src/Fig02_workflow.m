%% FIG3_FLOWCHART  Three-phase MATLAB-FEBio-MATLAB workflow and design of computational experiments.
clear; close all;
here = fileparts(mfilename('fullpath')); addpath(here); addpath(fileparts(here));   % figures_src and package root
cfg = study_config();
fg = figure('Color','w','Position',[40 40 1500 820]); axes('Position',[0 0 1 1]); hold on; axis off;
axis([0 100 0 62]);
C1 = [0.87 0.92 0.98]; C2 = [0.99 0.90 0.80]; C3 = [0.88 0.96 0.88]; CH = [0.25 0.33 0.50]; CV = [0.96 0.94 0.85];
xc = [17 50 83]; w = 29; hb = 6.2; ys = [47.5 39.5 31.5 23.5 15.5];
hdr = {'Phase I - Pre-processing (MATLAB)', 'Phase II - FE solution (FEBio 4)', 'Phase III - TCD post-processing (MATLAB)'};
fc  = {C1, C2, C3};
L = [cfg.mat.L];
T{1} = {sprintf('Material data (Table 1)\nE, \\nu, \\sigma_0 = \\sigma_u, K_{Ic}  \\rightarrow  L = (1/\\pi)(K_{Ic}/\\sigma_0)^2'), ...
        sprintf('Topologies: Sinusoidal, Triangle, Dovetail (\\theta_u = %d\\circ)\nA/\\lambda = %.2f, scale s = %s', cfg.dovetail_undercut_deg, cfg.A0/cfg.lambda0, mat2str(cfg.scales)), ...
        sprintf('Interface-conforming structured mesh\nshared nodes, h = %.2f mm, growth %.2f, %d wavelengths', cfg.h_prod, cfg.growth, cfg.n_wave), ...
        sprintf('Quality control\npositive Jacobian at all corners, aspect ratio'), ...
        sprintf('FEBio input (.feb)\n9 material pairs per geometry')};
T{2} = {sprintf('2.5D plane strain, hex8 (one layer)\n\\epsilon_{zz} = 0'), ...
        sprintf('Neo-Hookean, small strain\n\\epsilon_{ref} = %.1f %%  (\\equiv linear elasticity)', 100*cfg.eps_ref), ...
        sprintf('BCs: u_y = 0 base, u_x = 0 one node\nu_y = U_{ref} on top (displacement control)'), ...
        sprintf('Two load steps: 0.5 U_{ref}, U_{ref}\nfull Newton, d_{tol} = 10^{-4}'), ...
        sprintf('Logfiles: element \\sigma_x, \\sigma_y, \\tau_{xy}\nnodal reactions R_y')};
T{3} = {sprintf('Reference load P_{ref} = \\Sigma R_y / t\n\\sigma_{nom} = P_{ref}/W'), ...
        sprintf('L/2 locus in each constituent\n(points at distance L/2 from the interface)'), ...
        sprintf('\\sigma_1 (primary), \\sigma_n/\\tau_t (mode mixity)\nI_f = (\\sigma_1/\\sigma_0)^2 at every locus point'), ...
        sprintf('Competing criterion\nP_{fail} = P_{ref}/\\surd max(I_{f,top}, I_{f,bottom})'), ...
        sprintf('Outputs: \\eta = \\sigma_f/\\sigma_{0,gov}, K(L/2), U_{fail}\nstress paths, envelopes')};
for p = 1:3
    flow_box(xc(p), 56.5, w, 4.5, hdr{p}, CH, 9, 'bold');
    set(findobj(gca,'Type','text','String',hdr{p}), 'Color','w');
    for k = 1:5
        flow_box(xc(p), ys(k), w, hb, T{p}{k}, fc{p}, 8);
        if k < 5, draw_arrow([xc(p) ys(k)-hb/2], [xc(p) ys(k+1)+hb/2], 'k', 1, 0.45); end
    end
end
draw_arrow([xc(1)+w/2 15.5], [xc(2)-w/2 47.5], [0.3 0.3 0.3], 1.3, 0.06);
draw_arrow([xc(2)+w/2 15.5], [xc(3)-w/2 47.5], [0.3 0.3 0.3], 1.3, 0.06);
nP = numel(cfg.topologies)*numel(cfg.scales)*9; nC = numel(cfg.topologies)*(numel(cfg.h_conv)-1)*size(cfg.conv_pairs,1);
flow_box(33.5, 5.5, 62, 7.5, sprintf(['Design of computational experiments: %d topologies \\times %d scales \\times 9 top/substrate pairs = %d models\n' ...
    '+ mesh convergence (h = %s mm, %d pairs) = %d models;  total %d FEBio analyses'], numel(cfg.topologies), numel(cfg.scales), nP, ...
    mat2str(cfg.h_conv), size(cfg.conv_pairs,1), nC, nP + nC), [0.93 0.93 0.93], 8.5);
flow_box(83, 5.5, w, 7.5, sprintf('Verification: linearity P(0.5U)/P(U), mono-material K = 1,\nwidth sensitivity, GCI mesh convergence, independent solver'), CV, 8);
save_fig600(fg, 'Fig02_workflow');
